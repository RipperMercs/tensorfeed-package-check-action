import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseYarnLock, berryPolicy } from '../src/lockfiles/yarn.mjs';

const pk = (name, version) => ({ ecosystem: 'npm', name, version });

const V1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.24.7":
  version "7.24.7"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.24.7.tgz#abc"
  integrity sha512-aaa

lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#def"

my-chalk@npm:chalk@^5.0.0:
  version "5.3.0"
  resolved "https://registry.yarnpkg.com/chalk/-/chalk-5.3.0.tgz#ghi"

"@corp/secret@^1.0.0":
  version "1.0.0"
  resolved "https://npm.pkg.github.com/download/@corp/secret/1.0.0/xyz"
`;

test('yarn v1: public entries, alias resolves to the real name, private skipped', () => {
  const r = parseYarnLock(V1, {});
  assert.deepEqual(r.entries, [pk('@babel/code-frame', '7.24.7'), pk('lodash', '4.17.21'), pk('chalk', '5.3.0')]);
  assert.equal(r.skipped, 1);
});

test('yarn v1 with CRLF parses the same', () => {
  assert.deepEqual(parseYarnLock(V1.replace(/\n/g, '\r\n'), {}).entries, parseYarnLock(V1, {}).entries);
});

const BERRY = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@babel/code-frame@npm:^7.0.0, @babel/code-frame@npm:^7.24.7":
  version: 7.24.7
  resolution: "@babel/code-frame@npm:7.24.7"
  languageName: node
  linkType: hard

"lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  languageName: node
  linkType: hard

"@corp/ui@npm:^2.0.0":
  version: 2.1.0
  resolution: "@corp/ui@npm:2.1.0"
  languageName: node
  linkType: hard

"resolve@patch:resolve@npm%3A^1.22.0#~builtin<compat/resolve>":
  version: 1.22.8
  resolution: "resolve@patch:resolve@npm%3A1.22.8#~builtin<compat/resolve>::version=1.22.8&hash=c3c19d"
  languageName: node
  linkType: hard

"my-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "my-app@workspace:."
  languageName: unknown
  linkType: soft
`;

test('yarn berry: npm: resolutions only; patch and workspace skipped', () => {
  const r = parseYarnLock(BERRY, { yarnrc: null });
  assert.deepEqual(r.entries, [pk('@babel/code-frame', '7.24.7'), pk('lodash', '4.17.21'), pk('@corp/ui', '2.1.0')]);
  assert.equal(r.skipped, 2);
});

test('yarn berry: .yarnrc.yml scopes and custom server skip entries', () => {
  const scoped = parseYarnLock(BERRY, { yarnrc: 'npmScopes:\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n' });
  assert.deepEqual(scoped.entries.map((e) => e.name), ['@babel/code-frame', 'lodash']);
  const all = parseYarnLock(BERRY, { yarnrc: 'npmRegistryServer: "https://npm.corp.example"\n' });
  assert.deepEqual(all.entries, []);
});

test('berryPolicy treats the public default as not private', () => {
  assert.equal(berryPolicy('npmRegistryServer: "https://registry.yarnpkg.com"\n').skipAll, false);
  assert.equal(berryPolicy(null).skipAll, false);
});

test('top-level JSON-flow npmRegistryServer fails closed', () => {
  const flowYarnrc = '{"npmRegistryServer": "https://npm.corp.example"}\n';
  const policy = berryPolicy(flowYarnrc);
  assert.equal(policy.skipAll, true);
  const r = parseYarnLock(BERRY, { yarnrc: flowYarnrc });
  assert.deepEqual(r.entries, []);
});

test('npmRegistryServer whose value is on the next line fails closed', () => {
  const yarnrc = 'npmRegistryServer:\n  "https://npm.corp.example"\n';
  const policy = berryPolicy(yarnrc);
  assert.equal(policy.skipAll, true);
  const r = parseYarnLock(BERRY, { yarnrc });
  assert.deepEqual(r.entries, []);
});

test('a scoped npmRegistryServer nested under npmScopes does not trip the new fallback', () => {
  const yarnrc = 'npmScopes:\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n';
  const policy = berryPolicy(yarnrc);
  assert.equal(policy.skipAll, false);
  assert.deepEqual([...policy.privateScopes], ['@corp']);
});

test('flow-style npmScopes: fail closed on flow map syntax', () => {
  const flowYarnrc = 'npmScopes: {corp: {npmRegistryServer: "https://npm.corp.example"}}\n';
  const policy = berryPolicy(flowYarnrc);
  assert.equal(policy.skipAll, true);
  const r = parseYarnLock(BERRY, { yarnrc: flowYarnrc });
  assert.deepEqual(r.entries, []);
});

test('bare-host default registries work with and without scheme', () => {
  assert.equal(berryPolicy('npmRegistryServer: "registry.yarnpkg.com"\n').skipAll, false);
  assert.equal(berryPolicy('npmRegistryServer: "registry.npmjs.org/"\n').skipAll, false);
  assert.equal(berryPolicy('npmRegistryServer: "registry.yarnpkg.com/"\n').skipAll, false);
  assert.equal(berryPolicy('npmRegistryServer: "npm.corp.example"\n').skipAll, true);
});

test('UTF-8 BOM in yarnrc and lockfile is stripped', () => {
  const bomYarnrc = '\uFEFFnpmRegistryServer: "https://npm.corp.example"\n';
  const policy = berryPolicy(bomYarnrc);
  assert.equal(policy.skipAll, true);
  const bomV1 = '\uFEFF# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n\n"lodash@^4.17.21":\n  version "4.17.21"\n  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#def"\n';
  const r = parseYarnLock(bomV1, {});
  assert.deepEqual(r.entries, [pk('lodash', '4.17.21')]);
});

test('npmScopes header with trailing comment: block still parsed', () => {
  const yarnrc = 'npmScopes: # corp registries\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n';
  const r = parseYarnLock(BERRY, { yarnrc });
  assert.deepEqual(r.entries.map((e) => e.name), ['@babel/code-frame', 'lodash']);
});

test('npmScopes header with anchor fails closed', () => {
  const yarnrc = 'npmScopes: &scopes\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n';
  const policy = berryPolicy(yarnrc);
  assert.equal(policy.skipAll, true);
  const r = parseYarnLock(BERRY, { yarnrc });
  assert.deepEqual(r.entries, []);
});

test('npmScopes header with tag fails closed', () => {
  const yarnrc = 'npmScopes: !!map\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n';
  const policy = berryPolicy(yarnrc);
  assert.equal(policy.skipAll, true);
  const r = parseYarnLock(BERRY, { yarnrc });
  assert.deepEqual(r.entries, []);
});

test('scope line with trailing comment: @corp/ui skipped', () => {
  const yarnrc = 'npmScopes:\n  corp: # ours\n    npmRegistryServer: "https://npm.corp.example"\n';
  const r = parseYarnLock(BERRY, { yarnrc });
  assert.deepEqual(r.entries.map((e) => e.name), ['@babel/code-frame', 'lodash']);
});

test('scope value as flow map: @corp/ui skipped', () => {
  const yarnrc = 'npmScopes:\n  corp: {npmRegistryServer: "https://npm.corp.example"}\n';
  const r = parseYarnLock(BERRY, { yarnrc });
  assert.deepEqual(r.entries.map((e) => e.name), ['@babel/code-frame', 'lodash']);
});

test('two scopes at same indent plus nested settings: both detected, settings ignored', () => {
  const yarnrc = 'npmScopes:\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n  acme:\n    npmAuthToken: "secret"\n';
  const policy = berryPolicy(yarnrc);
  assert.deepEqual(Array.from(policy.privateScopes).sort(), ['@acme', '@corp']);
});

test('quoted npmRegistryServer key: skipAll true', () => {
  const yarnrc = '"npmRegistryServer": "https://npm.corp.example"\n';
  const policy = berryPolicy(yarnrc);
  assert.equal(policy.skipAll, true);
});

test("quoted npmScopes key: skips if block can't be parsed", () => {
  const yarnrc = '"npmScopes":\n  corp:\n    npmRegistryServer: "https://npm.corp.example"\n';
  const policy = berryPolicy(yarnrc);
  assert.deepEqual(Array.from(policy.privateScopes), ['@corp']);
});

test('a commented-out npmScopes line does not disable every Berry check', () => {
  const policy = berryPolicy('# npmScopes are set per machine\nnpmRegistryServer: "https://registry.yarnpkg.com"\n');
  assert.equal(policy.skipAll, false);
  assert.deepEqual(parseYarnLock(BERRY, { yarnrc: '  # npmScopes:\n' }).entries.map((e) => e.name), ['@babel/code-frame', 'lodash', '@corp/ui']);
  assert.equal(berryPolicy('packageExtensions:\n  npmScopes: x\n').skipAll, true);
});

test('yarn berry: a policy passed in wins over yarnrc text and skipped entries are counted', () => {
  const r = parseYarnLock(BERRY, { yarnrc: null, policy: { skipAll: false, privateScopes: new Set(['@corp']) } });
  assert.deepEqual(r.entries.map((e) => e.name), ['@babel/code-frame', 'lodash']);
  assert.equal(r.registrySkipped, 1);
  assert.equal(r.skipped, 3);
  const all = parseYarnLock(BERRY, { policy: { skipAll: true, privateScopes: new Set() } });
  assert.deepEqual(all.entries, []);
  assert.equal(all.registrySkipped, 3);
});
