import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parsePoetryLock } from '../src/lockfiles/poetry.mjs';
import { parseUvLock } from '../src/lockfiles/uv.mjs';
import { parseRequirements } from '../src/lockfiles/requirements.mjs';

const pk = (name, version) => ({ ecosystem: 'pypi', name, version });

const POETRY = `# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.

[[package]]
name = "requests"
version = "2.32.3"
description = "Python HTTP for Humans."
optional = false
python-versions = ">=3.8"
files = [
    {file = "requests-2.32.3-py3-none-any.whl", hash = "sha256:aaa"},
]

[package.dependencies]
certifi = ">=2017.4.17"

[[package]]
name = "corp-sdk"
version = "1.4.0"
description = ""
optional = false
python-versions = "*"
files = []

[package.source]
type = "legacy"
url = "https://pypi.corp.example/simple"
reference = "corp"

[[package]]
name = "mirror-ok"
version = "0.1.0"
description = ""
optional = false
python-versions = "*"
files = []

[package.source]
type = "legacy"
url = "https://pypi.org/simple"
reference = "pypi-explicit"

[metadata]
lock-version = "2.0"
`;

test('poetry: public packages only; custom sources skipped', () => {
  const r = parsePoetryLock(POETRY);
  assert.deepEqual(r.entries, [pk('requests', '2.32.3'), pk('mirror-ok', '0.1.0')]);
  assert.equal(r.skipped, 1);
  assert.deepEqual(parsePoetryLock(POETRY.replace(/\n/g, '\r\n')).entries, r.entries);
});

const UV = `version = 1
requires-python = ">=3.12"

[[package]]
name = "certifi"
version = "2024.8.30"
source = { registry = "https://pypi.org/simple" }
sdist = { url = "https://files.pythonhosted.org/packages/certifi-2024.8.30.tar.gz", hash = "sha256:bbb", size = 1 }

[[package]]
name = "httpx"
version = "0.27.2"
source = { registry = "https://pypi.org/simple" }
dependencies = [
    { name = "certifi" },
]

[[package]]
name = "internal-lib"
version = "0.3.0"
source = { registry = "https://pypi.corp.example/simple" }

[[package]]
name = "myproj"
version = "0.1.0"
source = { editable = "." }

[package.optional-dependencies]
dev = [
    { name = "pytest" },
]
`;

test('uv: pypi registry entries only; nested name lines ignored', () => {
  const r = parseUvLock(UV);
  assert.deepEqual(r.entries, [pk('certifi', '2024.8.30'), pk('httpx', '0.27.2')]);
  assert.equal(r.skipped, 2);
  assert.deepEqual(parseUvLock(UV.replace(/\n/g, '\r\n')).entries, r.entries);
});

test('requirements: exact pins, extras, markers, hashes, continuations', () => {
  const txt = [
    '# comment',
    'requests==2.32.3',
    'Django[argon2]==5.0.6 ; python_version >= "3.10"',
    'urllib3==2.2.2 \\',
    '    --hash=sha256:ccc',
    'flask>=3.0',
    '-r other.txt',
    '-e .',
    './local-pkg',
    'pkg @ https://example.com/pkg.whl',
    'numpy===1.26.4',
  ].join('\n');
  const r = parseRequirements(txt);
  assert.deepEqual(r.entries, [pk('requests', '2.32.3'), pk('Django', '5.0.6'), pk('urllib3', '2.2.2'), pk('numpy', '1.26.4')]);
  assert.equal(r.skipped, 2);
});

test('requirements with a custom index skips the whole file', () => {
  for (const line of ['--index-url https://corp/simple', '-i https://corp/simple', '--extra-index-url https://corp/simple', '-f ./wheels', '--find-links=./wheels']) {
    const r = parseRequirements(`${line}\nrequests==2.32.3\n`);
    assert.deepEqual(r, { entries: [], skipped: 0, skippedFile: 'custom_index' }, line);
  }
});

test('requirements with CRLF parses the same', () => {
  assert.deepEqual(parseRequirements('requests==2.32.3\r\nflask==3.0.3\r\n').entries, [pk('requests', '2.32.3'), pk('flask', '3.0.3')]);
});

test('requirements: index options written without a space are caught too', () => {
  for (const line of ['-ihttps://corp/simple', '-f./wheels', '--index-url=https://corp/simple', '  --extra-index-url https://corp', '--find-links=/wheels', '-i=https://corp/simple']) {
    const r = parseRequirements(`${line}\nsecret-lib==1.0.0\n`);
    assert.deepEqual(r, { entries: [], skipped: 0, skippedFile: 'custom_index' }, line);
  }
});

test('requirements: abbreviated long index options count once they name at least one letter after "--"', () => {
  for (const line of ['--index https://corp/simple', '--ind=https://corp/simple', '--index-u https://corp', '--extra https://corp', '--ext=https://corp', '--find ./wheels', '--fin=./wheels', '--in https://corp/simple', '--ex x', '--fi x']) {
    assert.deepEqual(parseRequirements(`${line}\nsecret-lib==1.0.0\n`), { entries: [], skipped: 0, skippedFile: 'custom_index' }, line);
  }
  for (const line of ['--no-index', '--pre']) {
    assert.equal(parseRequirements(`${line}\nrequests==2.32.3\n`).skippedFile, undefined, line);
  }
});

test('requirements: --pypi-url and its shortened forms count as an index option', () => {
  for (const line of ['--pypi-url https://corp/simple', '--pypi https://corp/simple', '--p https://corp/simple', '--pypi-url=https://corp/simple']) {
    assert.deepEqual(parseRequirements(`${line}\nsecret-lib==1.0.0\n`), { entries: [], skipped: 0, skippedFile: 'custom_index' }, line);
  }
});
